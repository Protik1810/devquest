/** A small deterministic random generator, so a seed always gives the same shuffle (e.g. per exercise). */
export function seededRandom(seed: string) {
  let h = 2166136261;
  for (const c of seed) h = Math.imul(h ^ c.charCodeAt(0), 16777619);
  return () => {
    h = Math.imul(h ^ (h >>> 15), 2246822507);
    h = Math.imul(h ^ (h >>> 13), 3266489909);
    h ^= h >>> 16;
    return (h >>> 0) / 4294967296;
  };
}

/** A shuffled copy (Fisher–Yates). With a seed the order is repeatable; without one it's fresh each time. */
export function shuffled<T>(items: readonly T[], seed?: string): T[] {
  const rand = seed === undefined ? Math.random : seededRandom(seed);
  const out = [...items];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
